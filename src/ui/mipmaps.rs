//! The Mipmaps tab of a texture source: the chain the build writes, and its `.amipmap`; see
//! docs/features/mipmaps.md#mipmaps-tab.

use std::collections::BTreeMap;
use std::path::Path;

use bevy_egui::egui::{
    self, Align2, FontId, Frame, Margin, Painter, RichText, Sense, Ui, pos2, vec2,
};

use super::material_edit::{fixed, help_line, key_row};
use super::{Inspected, property_style};
use crate::inspect::MipChain;
use crate::mipmap::{self, Amipmap};
use crate::theme::{ACCENT, BG_HEADER, CHANNEL_R, TEXT, TEXT_WEAK};

/// A texture source's `.amipmap` being edited.
pub struct MipmapEdit {
    /// `None`: the texture has no `.amipmap`.
    edit: Option<Amipmap>,
    /// What the file holds, or why it cannot be read.
    saved: Result<Option<Amipmap>, String>,
    /// The texture's file name.
    name: String,
    /// Its levels by name: the file name of each.
    named: BTreeMap<u32, String>,
    /// The other texture sources of the input, relative to the texture's folder; the ones in
    /// that folder first.
    files: Vec<String>,
}

/// What the tab asks for.
pub enum Save {
    Write(Amipmap),
    /// Remove the `.amipmap`.
    Delete,
}

/// Reads what the tab edits for the texture source `file` under `input`.
pub fn prepare(input: &Path, file: &Path) -> MipmapEdit {
    let saved = mipmap::read(file);
    let dir = file.parent().unwrap_or(input);
    let mut files: Vec<String> = crate::build::files_under(input)
        .into_iter()
        .filter(|f| crate::build::is_texture_source(f) && f != file)
        .map(|f| crate::adata::relative(dir, &f))
        .collect();
    // The texture's own folder first: its levels are most likely there.
    files.sort_by_key(|f| (f.contains('/'), f.clone()));
    let mut named = BTreeMap::new();
    for (level, path) in mipmap::named_files(file) {
        let name = path.file_name().unwrap_or_default().to_string_lossy();
        named.entry(level).or_insert_with(|| name.into_owned());
    }
    MipmapEdit {
        edit: saved.clone().unwrap_or_default(),
        saved,
        name: file
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned(),
        named,
        files,
    }
}

/// The tab; `choice` is the level the canvas shows. Returns what to save once nothing is
/// being dragged or typed into.
pub fn source_tab(ui: &mut Ui, inspected: &mut Inspected, choice: &mut usize) -> Option<Save> {
    let edit = inspected.mipmap.as_mut()?;
    let chain = inspected.inspection.mip_chain.as_ref();
    let mut save = None;
    egui::ScrollArea::vertical()
        .auto_shrink(false)
        .show(ui, |ui| {
            Frame::new().inner_margin(Margin::same(8)).show(ui, |ui| {
                property_style(ui);
                let problem = match &edit.saved {
                    Err(e) => Some(e.as_str()),
                    Ok(_) => chain.and_then(|c| c.problem.as_deref()),
                };
                if let Some(problem) = problem {
                    ui.add(egui::Label::new(RichText::new(problem).color(CHANNEL_R)).wrap());
                }
                // A file that does not parse can only be removed here.
                let unreadable = edit.saved.is_err();
                let mut on = edit.edit.is_some() || unreadable;
                if ui.checkbox(&mut on, "Custom mip chain").changed() {
                    if on {
                        edit.edit = Some(Amipmap::default());
                    } else {
                        edit.edit = None;
                        save = Some(Save::Delete);
                    }
                }
                match (&mut edit.edit, chain) {
                    (Some(amipmap), Some(chain)) => levels_row(ui, amipmap, chain),
                    (None, Some(_)) if !unreadable => help_line(
                        ui,
                        "Generated by assetc. Turn it on to choose how many levels the texture \
                         has and to use your own image for any of them.",
                    ),
                    (_, None) => help_line(ui, "This file is not built as a texture of its own."),
                    _ => {}
                }
                if edit.edit.is_some() {
                    let stem = crate::build::strip_extension(&edit.name);
                    help_line(
                        ui,
                        &format!(
                            "Levels come from the files chosen below, else from files named \
                             {stem}.mip<n>.<ext> next to the texture, else they are generated \
                             from the level above."
                        ),
                    );
                }
                let Some(chain) = chain else {
                    return;
                };
                ui.add_space(4.0);
                if let Some(row) = level_rows(ui, chain, &edit.name, *choice) {
                    *choice = row;
                }
                let level = (*choice).min(chain.levels.len().saturating_sub(1));
                if level > 0
                    && let Some(amipmap) = &mut edit.edit
                {
                    ui.add_space(4.0);
                    file_row(ui, amipmap, level as u32, &edit.named, &edit.files);
                }
            });
        });
    if save.is_some() {
        return save;
    }
    let busy = ui.input(|i| i.pointer.any_down()) || ui.memory(|m| m.focused().is_some());
    let edit = inspected.mipmap.as_mut()?;
    let saved = edit.saved.as_ref().ok()?;
    if busy || edit.edit == *saved {
        return None;
    }
    let mut amipmap = edit.edit.clone()?;
    // A level past `levels` cannot keep its file.
    if let Some(levels) = amipmap.levels {
        amipmap.files.retain(|level, _| *level < levels);
    }
    edit.edit = Some(amipmap.clone());
    edit.saved = Ok(Some(amipmap.clone()));
    Some(Save::Write(amipmap))
}

/// How many levels the texture gets: the full chain until set.
fn levels_row(ui: &mut Ui, amipmap: &mut Amipmap, chain: &MipChain) {
    let full = chain.full.max(1) as u32;
    let mut levels = amipmap.levels.unwrap_or(full).min(full);
    let mut changed = false;
    let hint = "levels: how many levels are written, level 0 included";
    let reset = key_row(
        ui,
        ["Levels", hint],
        "",
        amipmap.levels.is_some(),
        |ui, width| {
            let field = egui::DragValue::new(&mut levels)
                .range(1..=full)
                .speed(0.05);
            changed = ui.add_sized(vec2(width, 22.0), field).changed();
        },
    );
    if reset {
        amipmap.levels = None;
    } else if changed {
        amipmap.levels = Some(levels);
    }
}

/// One row per level: its number, size and where it comes from (a chosen file in `ACCENT`,
/// as what the `.amipmap` sets is), with its problem below; returns the clicked row.
fn level_rows(ui: &mut Ui, chain: &MipChain, texture: &str, chosen: usize) -> Option<usize> {
    let mut clicked = None;
    ui.scope(|ui| {
        ui.spacing_mut().item_spacing.y = 0.0;
        for (i, level) in chain.levels.iter().enumerate() {
            let (rect, response) =
                ui.allocate_exact_size(vec2(ui.available_width(), 28.0), Sense::click());
            let painter = ui.painter();
            if chosen == i {
                painter.rect_filled(rect, 0.0, ACCENT.gamma_multiply(0.25));
            } else if response.hovered() {
                painter.rect_filled(rect, 0.0, BG_HEADER);
            }
            let y = rect.center().y;
            let label = painter.text(
                pos2(rect.left() + 10.0, y),
                Align2::LEFT_CENTER,
                format!("Level {i}"),
                FontId::proportional(14.0),
                TEXT,
            );
            let size = painter.text(
                pos2(rect.right() - 10.0, y),
                Align2::RIGHT_CENTER,
                format!("{} × {}", level.width, level.height),
                FontId::proportional(13.0),
                TEXT_WEAK,
            );
            let (source, color, hover) = match &level.file {
                _ if i == 0 => (texture, TEXT_WEAK, "The texture itself".to_owned()),
                Some((file, true)) => (file.as_str(), TEXT_WEAK, format!("{file}, by its name")),
                Some((file, false)) => (file.as_str(), ACCENT, format!("{file}, chosen")),
                None => (
                    "Generated",
                    TEXT_WEAK,
                    format!("Generated from level {}", i - 1),
                ),
            };
            let room = size.left() - label.right() - 24.0;
            let font = FontId::proportional(13.0);
            painter.text(
                pos2(label.right() + 12.0, y),
                Align2::LEFT_CENTER,
                elide_start(painter, source, &font, room),
                font,
                color,
            );
            if response.clicked() {
                clicked = Some(i);
            }
            response.on_hover_text(hover);
            if let Some(problem) = &level.problem {
                Frame::new()
                    .inner_margin(Margin::symmetric(10, 2))
                    .show(ui, |ui| {
                        let text = RichText::new(problem).size(12.0).color(CHANNEL_R);
                        ui.add(egui::Label::new(text).wrap());
                    });
            }
        }
    });
    clicked
}

/// `text`, with its start cut to `…` until it is at most `width` wide.
fn elide_start(painter: &Painter, text: &str, font: &FontId, width: f32) -> String {
    let fits = |text: &str| {
        painter
            .layout_no_wrap(text.to_owned(), font.clone(), TEXT_WEAK)
            .size()
            .x
            <= width
    };
    if fits(text) {
        return text.to_owned();
    }
    let chars: Vec<char> = text.chars().collect();
    (1..chars.len())
        .map(|skip| format!("…{}", chars[skip..].iter().collect::<String>()))
        .find(|cut| fits(cut))
        .unwrap_or_default()
}

/// The file of level `level`: by name until one is chosen.
fn file_row(
    ui: &mut Ui,
    amipmap: &mut Amipmap,
    level: u32,
    named: &BTreeMap<u32, String>,
    files: &[String],
) {
    let set = amipmap.files.get(&level).cloned();
    let by_name = match named.get(&level) {
        Some(file) => format!("By name: {file}"),
        None => "By name: none".to_owned(),
    };
    let text = match &set {
        Some(path) => RichText::new(path),
        None => RichText::new(&by_name).color(TEXT_WEAK),
    };
    let mut choice: Option<Option<String>> = None;
    let label = format!("Level {level} file");
    let hint = format!("[files] {level}: the image of level {level}");
    let reset = key_row(ui, [&label, &hint], "", set.is_some(), |ui, width| {
        fixed(ui, width, |ui| {
            egui::ComboBox::from_id_salt("amipmap_level_file")
                .width(width)
                .truncate()
                .selected_text(text)
                .show_ui(ui, |ui| {
                    if ui.selectable_label(set.is_none(), &by_name).clicked() {
                        choice = Some(None);
                    }
                    for file in files {
                        let on = set.as_deref() == Some(file.as_str());
                        if ui.selectable_label(on, file).clicked() {
                            choice = Some(Some(file.clone()));
                        }
                    }
                });
        });
    });
    if reset {
        choice = Some(None);
    }
    match choice {
        Some(Some(path)) => {
            amipmap.files.insert(level, path);
        }
        Some(None) => {
            amipmap.files.remove(&level);
        }
        None => {}
    }
}
